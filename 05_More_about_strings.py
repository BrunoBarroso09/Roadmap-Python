#More about strings

#New line \n
string = 'I\'m a\nstring'
print(string)

#Indentation \t
string = 'I\'m a\n\tstring'
print(string)

#len - string length
string = 'I\'m a string'
print(len(string))

#upper - All characters in upper case
string = 'I\'m a string'
print(string.upper())

#lower - All characters in lower case
string = 'I\'m a string'
print(string.lower())